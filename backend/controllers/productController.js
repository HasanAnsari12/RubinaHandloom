const Product = require("../models/Product");
const { deleteImage } = require("../services/cloudinaryService");

// Get all products
const getProducts = async (req, res) => {
  try {
    const products = await Product.find().sort({ createdAt: -1 });

    res.status(200).json({
      success: true,
      count: products.length,
      products,
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};

// Get single product
const getProductById = async (req, res) => {
  try {
    const product = await Product.findById(req.params.id);

    if (!product) {
      return res.status(404).json({
        success: false,
        message: "Product not found",
      });
    }

    res.status(200).json({
      success: true,
      product,
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};

// Create product
const createProduct = async (req, res) => {
  try {
    const product = await Product.create(req.body);

    res.status(201).json({
      success: true,
      message: "Product created successfully",
      product,
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};

// Update product
const updateProduct = async (req, res) => {
  try {
    const product = await Product.findById(req.params.id);

    if (!product) {
      return res.status(404).json({
        success: false,
        message: "Product not found",
      });
    }

    // Identify and delete removed images from Cloudinary automatically
    if (req.body.images && Array.isArray(req.body.images)) {
      const oldImages = product.images || [];
      const newImages = req.body.images;

      const removedImages = oldImages.filter(
        (oldImg) => !newImages.some((newImg) => newImg.public_id === oldImg.public_id)
      );

      for (const img of removedImages) {
        if (img.public_id && img.public_id !== "legacy") {
          try {
            await deleteImage(img.public_id);
          } catch (cloudinaryErr) {
            console.error(
              `Failed to delete removed image ${img.public_id} from Cloudinary:`,
              cloudinaryErr.message
            );
          }
        }
      }
    }

    // Apply updates and trigger validation rules on save
    Object.assign(product, req.body);
    await product.save();

    res.status(200).json({
      success: true,
      message: "Product updated successfully",
      product,
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};

// Delete product
const deleteProduct = async (req, res) => {
  try {
    const product = await Product.findById(req.params.id);

    if (!product) {
      return res.status(404).json({
        success: false,
        message: "Product not found",
      });
    }

    // Delete associated images from Cloudinary
    if (product.images && product.images.length > 0) {
      for (const img of product.images) {
        if (img.public_id) {
          try {
            await deleteImage(img.public_id);
          } catch (cloudinaryErr) {
            console.error(
              `Failed to delete Cloudinary image ${img.public_id}:`,
              cloudinaryErr.message
            );
          }
        }
      }
    }

    await product.deleteOne();

    res.status(200).json({
      success: true,
      message: "Product deleted successfully",
    });
  } catch (error) {
    res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};

module.exports = {
  getProducts,
  getProductById,
  createProduct,
  updateProduct,
  deleteProduct,
};