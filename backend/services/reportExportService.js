/**
 * Formats report rows and summary headers into standard CSV spreadsheets.
 * Prefixes UTF-8 BOM (\ufeff) so Excel parses Unicode characters natively.
 */

const obfuscateEmail = (email) => {
  if (!email || email === "N/A" || email === "[HIDDEN]") return "[HIDDEN]";
  const parts = email.split("@");
  if (parts.length !== 2) return "[HIDDEN]";
  const name = parts[0];
  if (name.length <= 2) return `*@${parts[1]}`;
  return `${name[0]}***${name[name.length - 1]}@${parts[1]}`;
};

const obfuscatePhone = (phone) => {
  if (!phone || phone === "[HIDDEN]") return "[HIDDEN]";
  if (phone.length < 4) return "****";
  return `******${phone.slice(-4)}`;
};

const escapeCsvField = (field) => {
  if (field === null || field === undefined) return "";
  let str = String(field);
  if (str.includes(",") || str.includes('"') || str.includes("\n") || str.includes("\r")) {
    str = str.replace(/"/g, '""');
    return `"${str}"`;
  }
  return str;
};

const generateCsvReport = ({
  reportType,
  rows = [],
  summary = {},
  filters = {},
  adminName = "Admin",
  selectedColumns = [], // Custom selected columns subset
  obfuscateSensitive = false,
}) => {
  // 1. Prefix Unicode UTF-8 BOM
  let csvText = "\ufeff";

  // 2. Write Metadata Header
  csvText += `SRK Handloom\r\n`;
  csvText += `${reportType} Report\r\n`;
  
  // Format current date timezone-ready
  const genTime = new Date().toLocaleString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hour12: true,
  }) + " IST";
  
  csvText += `Generated At: ${genTime}\r\n`;
  csvText += `Generated By: ${adminName}\r\n`;

  const startStr = filters.startDate ? new Date(filters.startDate).toLocaleDateString("en-IN") : "Lifetime";
  const endStr = filters.endDate ? new Date(filters.endDate).toLocaleDateString("en-IN") : "Today";
  csvText += `Date Range: ${startStr} - ${endStr}\r\n`;

  const filterStrings = [];
  Object.keys(filters).forEach((key) => {
    if (key !== "startDate" && key !== "endDate" && filters[key]) {
      filterStrings.push(`${key} = ${filters[key]}`);
    }
  });
  csvText += `Applied Filters: ${filterStrings.join(", ") || "None"}\r\n`;
  csvText += `Total Records: ${rows.length}\r\n`;
  csvText += `\r\n`; // Empty line spacer

  // 3. Define Table Columns mapping based on Report Category
  let defaultColumns = [];
  if (reportType === "Sales") {
    defaultColumns = [
      { label: "Date / Period", key: "dateGroup" },
      { label: "Orders Count", key: "ordersCount" },
      { label: "Gross Revenue (₹)", key: "revenue" },
      { label: "Discounts (₹)", key: "discount" },
      { label: "Shipping (₹)", key: "shippingCharge" },
      { label: "Mock GST Tax (₹)", key: "tax" },
      { label: "Refunds Count", key: "refundsCount" },
      { label: "Refunds Amount (₹)", key: "refundsAmount" },
      { label: "AOV (₹)", key: "aov" },
    ];
  } else if (reportType === "Orders") {
    defaultColumns = [
      { label: "Order ID", key: "orderId" },
      { label: "Customer Name", key: "customerName" },
      { label: "Customer Email", key: "customerEmail" },
      { label: "Subtotal (₹)", key: "subtotal" },
      { label: "Discount (₹)", key: "discount" },
      { label: "Shipping (₹)", key: "shippingCharge" },
      { label: "Total Amount (₹)", key: "totalAmount" },
      { label: "Order Status", key: "orderStatus" },
      { label: "Payment Method", key: "paymentMethod" },
      { label: "Payment Status", key: "paymentStatus" },
      { label: "Date", key: "date" },
    ];
  } else if (reportType === "Products") {
    defaultColumns = [
      { label: "Product Title", key: "title" },
      { label: "Category", key: "category" },
      { label: "Price (₹)", key: "price" },
      { label: "Current Stock", key: "stock" },
      { label: "Status", key: "status" },
      { label: "Units Sold", key: "unitsSold" },
      { label: "Sales Revenue (₹)", key: "revenue" },
      { label: "Rating Stars", key: "rating" },
      { label: "Reviews Count", key: "numReviews" },
    ];
  } else if (reportType === "Customers") {
    defaultColumns = [
      { label: "Customer Name", key: "name" },
      { label: "Email Address", key: "email" },
      { label: "Phone Number", key: "phone" },
      { label: "Orders Placed", key: "ordersCount" },
      { label: "Lifetime Spend (₹)", key: "totalSpent" },
      { label: "Coupons Claimed", key: "couponsUsed" },
      { label: "Join Date", key: "joinedDate" },
    ];
  } else if (reportType === "Coupons") {
    defaultColumns = [
      { label: "Coupon Code", key: "code" },
      { label: "Campaign Title", key: "title" },
      { label: "Discount Type", key: "discountType" },
      { label: "Discount Value", key: "discountValue" },
      { label: "Status", key: "status" },
      { label: "Redemptions count", key: "usedCount" },
      { label: "Discounts Saved (₹)", key: "totalSavings" },
      { label: "Expiry Date", key: "validUntil" },
    ];
  } else if (reportType === "Reviews") {
    defaultColumns = [
      { label: "Product Title", key: "productTitle" },
      { label: "Customer Name", key: "customerName" },
      { label: "Customer Email", key: "customerEmail" },
      { label: "Stars Rating", key: "rating" },
      { label: "Moderation Status", key: "status" },
      { label: "Comment Text", key: "comment" },
      { label: "Date", key: "date" },
    ];
  }

  // Filter columns based on user Column Selector selection (if provided)
  const columnsToUse = selectedColumns.length > 0
    ? defaultColumns.filter((col) => selectedColumns.includes(col.key))
    : defaultColumns;

  // 4. Write CSV Table Headers
  const headers = columnsToUse.map((c) => escapeCsvField(c.label));
  csvText += headers.join(",") + "\r\n";

  // 5. Write CSV Table Data rows
  rows.forEach((row) => {
    const rowFields = columnsToUse.map((col) => {
      let val = row[col.key];

      // Format Date values beautifully in CSV
      if (val instanceof Date || (typeof val === "string" && !isNaN(Date.parse(val)) && (col.key === "date" || col.key === "joinedDate" || col.key === "validUntil"))) {
        val = new Date(val).toLocaleDateString("en-IN") + " " + new Date(val).toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" });
      }

      // Obfuscate sensitive variables if checked
      if (obfuscateSensitive) {
        if (col.key === "customerEmail" || col.key === "email") {
          val = obfuscateEmail(val);
        } else if (col.key === "phone") {
          val = obfuscatePhone(val);
        }
      }

      return escapeCsvField(val);
    });
    csvText += rowFields.join(",") + "\r\n";
  });

  // 6. Write Summaries totals footer (bottom row)
  csvText += `\r\n`;
  csvText += `Summary Totals\r\n`;
  
  if (reportType === "Sales") {
    csvText += `Total Revenue,₹${summary.totalRevenue || 0}\r\n`;
    csvText += `Total Orders,${summary.totalOrders || 0}\r\n`;
    csvText += `Total Discounts,₹${summary.totalDiscounts || 0}\r\n`;
    csvText += `Average Order Value (AOV),₹${summary.averageOrderValue || 0}\r\n`;
  } else if (reportType === "Orders") {
    csvText += `Total Amount,₹${summary.totalVolume || 0}\r\n`;
    csvText += `Total Orders,${summary.count || 0}\r\n`;
    csvText += `Total Discounts,₹${summary.totalDiscounts || 0}\r\n`;
  } else if (reportType === "Products") {
    csvText += `Total Products,${summary.totalProducts || 0}\r\n`;
    csvText += `Total Sold Units,${summary.totalSoldUnits || 0}\r\n`;
    csvText += `Total Sales Revenue,₹${summary.totalRevenue || 0}\r\n`;
    csvText += `Total Stock Value,₹${summary.totalStockValue || 0}\r\n`;
  } else if (reportType === "Customers") {
    csvText += `Total Customers,${summary.totalCustomers || 0}\r\n`;
    csvText += `Total Spent Amount,₹${summary.totalSpentAmount || 0}\r\n`;
    csvText += `Average Spend Per User,₹${summary.averageSpend || 0}\r\n`;
  } else if (reportType === "Coupons") {
    csvText += `Total Coupons,${summary.totalCoupons || 0}\r\n`;
    csvText += `Total Redemptions,${summary.totalClaimsCount || 0}\r\n`;
    csvText += `Total Savings,₹${summary.totalSavingsAmount || 0}\r\n`;
  } else if (reportType === "Reviews") {
    csvText += `Total Reviews,${summary.totalReviews || 0}\r\n`;
    csvText += `Average Stars Rating,${summary.averageRating || 0} ★\r\n`;
  }

  return csvText;
};

module.exports = {
  generateCsvReport,
};
